/*1. Built-in / Standard Exceptions

These are exceptions provided by the C++ Standard Library.

Examples:
- runtime_error
- logic_error
- out_of_range
- bad_alloc
2. User-defined Exceptions

These are exceptions created by the programmer according to the requirements of the program.

For example, we can create an exception for:
- Invalid age.
- Insufficient bank balance.
- Invalid marks.*/